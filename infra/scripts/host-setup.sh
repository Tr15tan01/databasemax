#!/usr/bin/env bash
# One-time preparation of an Ubuntu 24.04 VM for DatabaseMax (no Docker: everything runs under
# systemd). Run as root from the code checkout at /opt/databasemax. Idempotent.
#
#   sudo infra/scripts/host-setup.sh                 # control plane + data plane on one VM
#   sudo infra/scripts/host-setup.sh --role worker   # extra data-plane host (agent + provisioner)
#   sudo infra/scripts/host-setup.sh --no-ssh-hardening   # e.g. a local test VM
#
# Review before running: it changes SSH, firewall, PostgreSQL and Redis settings.
set -euo pipefail
ROLE=all
HARDEN_SSH=1
while [ $# -gt 0 ]; do
  case "$1" in
    --role) ROLE="$2"; shift 2 ;;
    --no-ssh-hardening) HARDEN_SSH=0; shift ;;
    *) echo "unknown option $1" >&2; exit 2 ;;
  esac
done
[ "$ROLE" = all ] || [ "$ROLE" = worker ] || { echo "--role must be all or worker" >&2; exit 2; }
[ "$(id -u)" = 0 ] || { echo "run as root" >&2; exit 1; }
ROOT="$(cd "$(dirname "$0")/../.." && pwd)"
[ "$ROOT" = /opt/databasemax ] || echo "warning: code is at $ROOT; the units expect /opt/databasemax" >&2
PG_VERSION="${DMX_PG_VERSION:-16}"
NODE_MAJOR=22
UV_VERSION=0.8.17
export DEBIAN_FRONTEND=noninteractive

echo "==> packages and automatic security updates"
apt-get update -y
apt-get install -y --no-install-recommends ca-certificates curl gnupg openssl git unzip jq age acl \
  unattended-upgrades fail2ban iptables netfilter-persistent iptables-persistent \
  e2fsprogs util-linux kmod python3 coreutils \
  "postgresql-$PG_VERSION" "postgresql-client-$PG_VERSION"
dpkg-reconfigure -f noninteractive unattended-upgrades

if [ "$ROLE" = all ]; then
  apt-get install -y --no-install-recommends redis-server debian-keyring debian-archive-keyring apt-transport-https
  install -m 0755 -d /etc/apt/keyrings
  if ! command -v caddy >/dev/null; then
    curl -fsSL https://dl.cloudsmith.io/public/caddy/stable/gpg.key | gpg --dearmor --yes -o /etc/apt/keyrings/caddy.gpg
    echo "deb [signed-by=/etc/apt/keyrings/caddy.gpg] https://dl.cloudsmith.io/public/caddy/stable/deb/debian any-version main" \
      > /etc/apt/sources.list.d/caddy-stable.list
    apt-get update -y && apt-get install -y caddy
  fi
  if ! node --version 2>/dev/null | grep -q "^v$NODE_MAJOR\."; then
    curl -fsSL https://deb.nodesource.com/gpgkey/nodesource-repo.gpg.key | gpg --dearmor --yes -o /etc/apt/keyrings/nodesource.gpg
    echo "deb [signed-by=/etc/apt/keyrings/nodesource.gpg] https://deb.nodesource.com/node_$NODE_MAJOR.x nodistro main" \
      > /etc/apt/sources.list.d/nodesource.list
    apt-get update -y && apt-get install -y nodejs
  fi
fi

echo "==> uv $UV_VERSION and Python 3.13 (for the services' virtual environments)"
if ! /usr/local/bin/uv --version 2>/dev/null | grep -q "$UV_VERSION"; then
  curl -LsSf "https://astral.sh/uv/$UV_VERSION/install.sh" | env UV_INSTALL_DIR=/usr/local/bin UV_NO_MODIFY_PATH=1 sh
fi
UV_PYTHON_INSTALL_DIR=/opt/databasemax-python /usr/local/bin/uv python install 3.13
chmod -R a+rX /opt/databasemax-python

if [ "$HARDEN_SSH" = 1 ]; then
  echo "==> SSH hardening (keys only)"
  install -d /etc/ssh/sshd_config.d
  cat > /etc/ssh/sshd_config.d/99-databasemax.conf <<'CONF'
PasswordAuthentication no
KbdInteractiveAuthentication no
PermitRootLogin no
MaxAuthTries 3
CONF
  systemctl reload ssh || systemctl reload sshd || true
fi

echo "==> service users"
for u in dmx-prov $( [ "$ROLE" = all ] && echo dmx-api dmx-web dmx-gw ); do
  id "$u" >/dev/null 2>&1 || useradd --system --user-group --no-create-home --home-dir /nonexistent \
    --shell /usr/sbin/nologin --comment "DatabaseMax $u" "$u"
done

echo "==> directories"
install -d -m 0711 /var/lib/databasemax /var/lib/databasemax/data-plane
install -d -m 0700 -o dmx-prov -g dmx-prov /var/lib/databasemax/provisioner /var/lib/databasemax/customer-backups
install -d -m 0700 /etc/databasemax /etc/databasemax/env /var/lib/databasemax/backups
if [ "$ROLE" = all ]; then
  install -d -m 0700 -o dmx-api -g dmx-api /var/lib/databasemax/mail
  install -d -m 0750 -o root -g dmx-gw /etc/databasemax/gateway-certs
fi
chmod 0755 "$ROOT"

echo "==> cgroup slice for customer databases"
ENV_FILE=/etc/databasemax/.env
val() { [ -f "$ENV_FILE" ] && sed -n "s/^$1=//p" "$ENV_FILE" | tail -n1 | tr -d "\"'" || true; }
MEM="$(val DMX_DATA_PLANE_MEMORY_MB)"; MEM="${MEM:-$(( $(awk '/MemTotal/ {print int($2/1024)}' /proc/meminfo) / 2 ))}"
CPUS="$(val DMX_DATA_PLANE_CPUS)"; CPUS="${CPUS:-1}"
cat > /etc/systemd/system/dmx-customers.slice <<SLICE
# All customer databases together may use at most the data-plane budget, so they can never
# starve the control plane. Regenerated by host-setup.sh from DMX_DATA_PLANE_*.
[Unit]
Description=DatabaseMax customer databases

[Slice]
MemoryAccounting=yes
MemoryMax=${MEM}M
CPUAccounting=yes
CPUQuota=$(awk "BEGIN {printf \"%d\", $CPUS * 100}")%
TasksMax=20000
SLICE

echo "==> systemd units"
install -m 0644 "$ROOT"/infra/systemd/*.service "$ROOT"/infra/systemd/*.target /etc/systemd/system/
install -m 0755 "$ROOT/infra/scripts/dmx-admin" /usr/local/bin/dmx-admin
[ -f /etc/databasemax/env/agent.env ] || printf "DMX_STORAGE_BACKEND='dir'\n" > /etc/databasemax/env/agent.env
chmod 600 /etc/databasemax/env/agent.env
systemctl daemon-reload
systemctl enable --now dmx-host-agent.service

if [ "$ROLE" = worker ]; then
  # Only the PostgreSQL binaries are needed here; the packaged cluster isn't used.
  pg_dropcluster --stop "$PG_VERSION" main 2>/dev/null || true
else
  echo "==> control-plane PostgreSQL (unix socket only: port 5432 belongs to the gateway)"
  CONF="/etc/postgresql/$PG_VERSION/main"
  cat > "$CONF/conf.d/databasemax.conf" <<'PGCONF'
# Managed by DatabaseMax host-setup.sh
listen_addresses = ''
max_connections = 200
shared_buffers = 256MB
password_encryption = scram-sha-256
PGCONF
  if ! grep -q "databasemax" "$CONF/pg_hba.conf"; then
    sed -i '0,/^local/s//# databasemax: control-plane roles authenticate with passwords\nlocal   dmx_control     dmx_owner,dmx_app                       scram-sha-256\n&/' "$CONF/pg_hba.conf"
  fi
  systemctl restart "postgresql@$PG_VERSION-main"

  echo "==> Redis (loopback only, no persistence; the password is set by deploy.sh)"
  cat > /etc/redis/databasemax.conf <<'REDIS'
# Managed by DatabaseMax host-setup.sh
bind 127.0.0.1 -::1
protected-mode yes
save ""
appendonly no
maxmemory 256mb
maxmemory-policy allkeys-lru
include /etc/redis/databasemax-auth.conf
REDIS
  [ -f /etc/redis/databasemax-auth.conf ] || install -m 0640 -o root -g redis /dev/null /etc/redis/databasemax-auth.conf
  chown root:redis /etc/redis/databasemax.conf && chmod 0640 /etc/redis/databasemax.conf
  grep -q "^include /etc/redis/databasemax.conf" /etc/redis/redis.conf || echo "include /etc/redis/databasemax.conf" >> /etc/redis/redis.conf
  systemctl restart redis-server

  echo "==> Caddy reads the domain from the rendered environment"
  install -d /etc/systemd/system/caddy.service.d
  cat > /etc/systemd/system/caddy.service.d/databasemax.conf <<'DROPIN'
[Service]
EnvironmentFile=-/etc/databasemax/env/caddy.env
DROPIN
  install -d -m 0755 -o caddy -g caddy /var/log/caddy
  systemctl daemon-reload
fi

echo "==> firewall: open only what must be public"
# Services bind to loopback except Caddy (80/443) and the gateway (5432). These rules make sure
# those ports are reachable on images that ship a default-reject INPUT chain (e.g. OCI Ubuntu).
for ipt in iptables ip6tables; do
  $ipt -N DMX-INPUT 2>/dev/null || $ipt -F DMX-INPUT
  if [ "$ROLE" = all ]; then
    $ipt -A DMX-INPUT -p tcp -m multiport --dports 80,443,5432 -m conntrack --ctstate NEW -j ACCEPT
    $ipt -A DMX-INPUT -p udp --dport 443 -j ACCEPT
  fi
  $ipt -A DMX-INPUT -j RETURN
  $ipt -C INPUT -j DMX-INPUT 2>/dev/null || $ipt -I INPUT 1 -j DMX-INPUT
done
netfilter-persistent save >/dev/null 2>&1 || true

echo
echo "done. Next:"
if [ "$ROLE" = worker ]; then
  echo "  infra/scripts/init-env.sh --worker --host-name <name> --private-ip <this VM> --gateway-ip <control VM>"
  echo "  then: dmx-admin firewall-plan on the control plane, and infra/scripts/deploy.sh local --role worker"
else
  echo "  infra/scripts/init-env.sh --domain <your domain> --email <you@example.com>   (or --dev)"
  echo "  gateway certificate in /etc/databasemax/gateway-certs (docs/deployment/oci.md §3)"
  echo "  infra/scripts/deploy.sh local"
fi
